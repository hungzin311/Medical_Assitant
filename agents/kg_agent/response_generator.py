from .cypher_query_llm import CypherQueryService
from .context_filter import ContextFilterEmbedding
from langchain_core.prompts import PromptTemplate
from llm_config import get_gemini_llm
from agents.patient_db_agent import PatientQueryEngine
prompt = PromptTemplate(
    template="""
    Bạn là bác sĩ AI chuyên nghiệp. Hãy trả lời câu hỏi dựa trên thông tin bệnh nhân và kiến thức y tế đã được lọc.

    THÔNG TIN BỆNH NHÂN:
    {patient_info}

    KIẾN THỨC Y TẾ LIÊN QUAN (đã được lọc phù hợp với bệnh nhân):
    {filtered_context}

    CÂU HỎI: {question}

    Hãy đưa ra lời khuyên cụ thể, phù hợp với:
    - Độ tuổi và giới tính của bệnh nhân
    - Tình trạng sức khỏe hiện tại
    - Tiền sử bệnh lý
    - Chỉ sử dụng thông tin đã được lọc

    TRẢ LỜI:
    """,
    input_variables=["patient_info", "filtered_context", "question"]
)

class ResponseGenerator:
    def __init__(self, patient_query_engine: PatientQueryEngine):
        self.cypher_query_llm = CypherQueryService()
        self.context_filter = ContextFilterEmbedding()
        self.llm = get_gemini_llm(temperature=0.2)
        self.patient_query_engine = patient_query_engine
    
    def generate_response(self, question: str, patient_id: str):
        # context from kg (cypher query generated by llm)
        kg_context = self.cypher_query_llm.retrieve_context_from_kg(question) 
        # patient profile
        patient_profile = self.patient_query_engine.get_patient_profile(patient_id)
        # filter context from kg 
        filtered_context = self.context_filter.filter_context(kg_context, patient_profile, question)
        # generate response
        response = self.llm.invoke(prompt.format(patient_info=patient_profile, 
                                                filtered_context=filtered_context, 
                                                question=question))
        return response.content
    